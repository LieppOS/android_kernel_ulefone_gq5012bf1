#!/usr/bin/env python3
"""Host-side tests for the LieppOS gen4m TKIP Michael MIC implementation.

The production file vendor/.../wlan/core/gen4m/mgmt/tkip_mic.c is compiled for
the host together with:

  * a generated precomp.h whose macros and struct field declarations are
    extracted verbatim from the gen4m driver headers (no hand-copied values);
  * the Linux mac80211 Michael implementation (net/mac80211/michael.c,
    GPL-2.0-only, Instant802 Networks) as an independent reference, with the
    frame-control/address helpers extracted from include/linux/ieee80211.h;
  * the IEEE 802.11 Michael test vectors extracted from crypto/testmgr.h
    (michael_mic_tv_template).

Everything generated goes to --work-dir; nothing is written to the source
tree. Usage:

  run-tests.py --work-dir <dir> [--cc gcc] [--iterations N]
"""
from __future__ import annotations

import argparse
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
KERNEL = os.path.abspath(os.path.join(HERE, "..", "..", "..", "..", ".."))
GEN4M = os.path.join(KERNEL, "vendor/mediatek/kernel_modules/connectivity/wlan/core/gen4m")
TKIP_MIC_C = os.path.join(GEN4M, "mgmt/tkip_mic.c")
MICHAEL_C = os.path.join(KERNEL, "net/mac80211/michael.c")
IEEE80211_H = os.path.join(KERNEL, "include/linux/ieee80211.h")
TESTMGR_H = os.path.join(KERNEL, "crypto/testmgr.h")

DRIVER_DEFINES = {
    "os/linux/include/gl_typedef.h": ["BIT", "BITS", "TRUE", "FALSE"],
    "include/nic/mac.h": [
        "MAC_ADDR_LEN", "TKIP_MIC_LEN", "WLAN_MAC_HEADER_LEN", "WLAN_MAC_HEADER_A4_LEN",
        "MASK_FC_TYPE", "MASK_FC_SUBTYPE", "MASK_FC_TO_DS", "MASK_FC_FROM_DS",
        "MASK_FRAME_TYPE", "MASK_TO_DS_FROM_DS", "MAC_FRAME_TYPE_DATA", "MAC_FRAME_QOS_DATA",
        "TID_NUM", "MASK_QC_TID", "ETHER_HEADER_LEN", "ETHER_TYPE_LEN_OFFSET",
        "ETHER_TYPE_MIN", "ETH_P_AARP", "ETH_P_IPX",
    ],
    "include/nic/nic_rx.h": ["RXM_IS_QOS_DATA_FRAME", "RXM_IS_FROM_DS_TO_DS",
                             "HAL_RX_STATUS_GET_FRAME_CTL_FIELD"],
    "include/mgmt/privacy.h": ["MIC_KEY_LEN"],
}
SW_RFB_FIELDS = ["pvHeader", "u2PacketLen", "u2HeaderLen", "u2PayloadLength",
                 "fgHdrTran", "ucGroupVLD", "prRxStatusGroup4", "ucTid"]
IEEE_DEFINES = ["IEEE80211_FCTL_FTYPE", "IEEE80211_FCTL_TODS", "IEEE80211_FCTL_FROMDS",
                "IEEE80211_FTYPE_DATA", "IEEE80211_STYPE_QOS_DATA", "IEEE80211_QOS_CTL_TID_MASK"]
IEEE_FUNCS = ["ieee80211_has_tods", "ieee80211_has_fromds", "ieee80211_has_a4",
              "ieee80211_is_data_qos", "ieee80211_get_qos_ctl", "ieee80211_get_tid",
              "ieee80211_get_SA", "ieee80211_get_DA"]


def read(path: str) -> str:
    with open(path, encoding="utf-8", errors="replace") as fh:
        return fh.read()


def extract_define(text: str, name: str) -> str:
    lines = text.splitlines()
    for i, line in enumerate(lines):
        if re.match(r"\s*#\s*define\s+" + re.escape(name) + r"\b", line):
            out = [line]
            while out[-1].rstrip().endswith("\\"):
                i += 1
                out.append(lines[i])
            return "\n".join(out)
    raise SystemExit(f"error: #define {name} not found")


def extract_block(text: str, start_re: str) -> str:
    m = re.search(start_re, text, re.M)
    if not m:
        raise SystemExit(f"error: {start_re} not found")
    i = text.index("{", m.start())
    depth = 0
    for j in range(i, len(text)):
        depth += {"{": 1, "}": -1}.get(text[j], 0)
        if depth == 0:
            end = j + 1
            if not re.search(r"\)\s*$", text[m.start():i]):
                # type or array definition: keep attributes up to the ';'
                end = text.index(";", end) + 1
            return text[m.start():end]
    raise SystemExit(f"error: unterminated block for {start_re}")


def gen_precomp(gen: str) -> None:
    parts = ["/* Generated by run-tests.py from the gen4m driver headers. */",
             "#include <stdint.h>", "#include <stddef.h>", "#include <sys/types.h>"]
    for rel, names in DRIVER_DEFINES.items():
        text = read(os.path.join(GEN4M, rel))
        parts.append(f"/* {rel} */")
        parts += [extract_define(text, n) for n in names]
    rx = read(os.path.join(GEN4M, "include/nic/nic_rx.h"))
    enum = extract_block(rx, r"^enum ENUM_MAC_RX_GROUP_VLD\b")
    names = [re.match(r"\s*(\w+)", e).group(1) for e in enum[enum.index("{") + 1:enum.rindex("}")].split(",")
             if re.match(r"\s*RX_GROUP_VLD_\d", e)]
    if names[0] != "RX_GROUP_VLD_1" or "= 0" not in enum:
        raise SystemExit("error: unexpected ENUM_MAC_RX_GROUP_VLD layout")
    parts.append(f"enum {{ RX_GROUP_VLD_4 = {names.index('RX_GROUP_VLD_4')} }};")
    parts.append(extract_block(read(os.path.join(GEN4M, "include/nic/nic_rxd_v2.h")),
                               r"^struct HW_MAC_RX_STS_GROUP_4 \{"))
    rfb = extract_block(rx, r"^struct SW_RFB \{")
    fields = []
    for f in SW_RFB_FIELDS:
        m = re.search(r"^\s*([\w\s\*]+?\b" + f + r")\s*;", rfb, re.M)
        if not m:
            raise SystemExit(f"error: SW_RFB field {f} not found")
        fields.append("\t" + " ".join(m.group(1).split()) + ";")
    parts.append("struct ADAPTER { int iUnused; };")
    parts.append("struct SW_RFB {  /* subset of the driver's struct SW_RFB */\n" +
                 "\n".join(fields) + "\n};")
    with open(os.path.join(gen, "precomp.h"), "w") as fh:
        fh.write("\n".join(parts) + "\n")


def gen_linux_shims(gen: str) -> None:
    os.makedirs(os.path.join(gen, "linux"), exist_ok=True)
    os.makedirs(os.path.join(gen, "asm"), exist_ok=True)
    with open(os.path.join(gen, "linux/types.h"), "w") as fh:
        fh.write("#pragma once\n#include <stdint.h>\n#include <stddef.h>\n#include <stdbool.h>\n"
                 "typedef uint8_t u8; typedef uint16_t u16; typedef uint32_t u32;\n"
                 "typedef uint16_t __le16;\n#define cpu_to_le16(x) ((__le16)(x))\n"
                 "#define ETH_ALEN 6\n#define __packed __attribute__((packed))\n"
                 "#define __aligned(x) __attribute__((aligned(x)))\n"
                 "#define struct_group(name, ...) __VA_ARGS__\n")
    with open(os.path.join(gen, "linux/bitops.h"), "w") as fh:
        fh.write("#pragma once\n#include <linux/types.h>\n"
                 "static inline u32 rol32(u32 w, unsigned int s) { return (w << (s & 31)) | (w >> ((-s) & 31)); }\n"
                 "static inline u32 ror32(u32 w, unsigned int s) { return (w >> (s & 31)) | (w << ((-s) & 31)); }\n")
    with open(os.path.join(gen, "asm/unaligned.h"), "w") as fh:
        fh.write("#pragma once\n#include <linux/types.h>\n"
                 "static inline u32 get_unaligned_le32(const void *p) { const u8 *b = p;"
                 " return b[0] | b[1] << 8 | b[2] << 16 | (u32)b[3] << 24; }\n"
                 "static inline u16 get_unaligned_le16(const void *p) { const u8 *b = p;"
                 " return b[0] | b[1] << 8; }\n"
                 "static inline void put_unaligned_le32(u32 v, void *p) { u8 *b = p;"
                 " b[0] = v; b[1] = v >> 8; b[2] = v >> 16; b[3] = v >> 24; }\n")
    text = read(IEEE80211_H)
    parts = ["#pragma once", "/* Extracted from include/linux/ieee80211.h by run-tests.py */",
             "#include <linux/types.h>"]
    parts += [extract_define(text, n) for n in IEEE_DEFINES]
    parts.append(extract_block(text, r"^struct ieee80211_hdr \{"))
    parts += [extract_block(text, r"^static inline \w+ \*?" + f + r"\(") for f in IEEE_FUNCS]
    with open(os.path.join(gen, "linux/ieee80211.h"), "w") as fh:
        fh.write("\n".join(parts) + "\n")
    with open(os.path.join(gen, "michael.h"), "w") as fh:
        fh.write(read(os.path.join(os.path.dirname(MICHAEL_C), "michael.h")))


def gen_vectors(gen: str) -> int:
    block = extract_block(read(TESTMGR_H), r"^static const struct hash_testvec michael_mic_tv_template\[\] =")
    vecs = []
    for ent in re.findall(r"\{(.*?)\}", block[block.index("=") + 1:], re.S):
        f = dict(re.findall(r"\.(\w+)\s*=\s*([^,\n]+),?", ent))
        if not f:
            continue
        pt = f["plaintext"].strip()
        pt = '""' if pt == "zeroed_string" else pt
        vecs.append(f"\t{{ {f['key'].strip()}, {pt}, {f['psize'].strip()}, {f['digest'].strip()} }},")
    with open(os.path.join(gen, "michael_vectors.h"), "w") as fh:
        fh.write("/* Extracted from crypto/testmgr.h michael_mic_tv_template */\n"
                 "static const struct { const char *key, *pt; size_t psize; const char *mic; } "
                 "michael_vectors[] = {\n" + "\n".join(vecs) + "\n};\n")
    return len(vecs)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--work-dir", required=True)
    ap.add_argument("--cc", default=os.environ.get("HOSTCC", "gcc"))
    ap.add_argument("--iterations", type=int, default=20000)
    args = ap.parse_args()

    work = os.path.abspath(args.work_dir)
    if (work + "/").startswith(KERNEL + "/"):
        raise SystemExit("error: --work-dir must be outside the source tree")
    gen = os.path.join(work, "gen")
    os.makedirs(gen, exist_ok=True)
    gen_precomp(gen)
    gen_linux_shims(gen)
    nvec = gen_vectors(gen)
    exe = os.path.join(work, "test_tkip_mic")
    ref_obj = os.path.join(work, "michael.o")
    common = [args.cc, "-std=gnu11", "-O1", "-g", "-Wall", "-Wextra", "-Werror",
              "-Wno-unused-parameter", "-Wno-sign-compare",
              "-fsanitize=address,undefined", "-fno-sanitize-recover=all", "-I", gen]
    # The kernel builds with -fno-strict-overflow; michael.c relies on
    # "u16 << 16" in int, so only the reference skips the shift check.
    ref_cmd = common + ["-fno-sanitize=shift", "-c", MICHAEL_C, "-o", ref_obj]
    cmd = common + [f'-DTKIP_MIC_SOURCE="{TKIP_MIC_C}"',
                    os.path.join(HERE, "test_tkip_mic.c"), ref_obj, "-o", exe]
    print("vectors extracted:", nvec)
    for c in (ref_cmd, cmd):
        print("$", " ".join(c))
        subprocess.run(c, check=True)
    return subprocess.run([exe, str(args.iterations)]).returncode


if __name__ == "__main__":
    sys.exit(main())
